function prog(id, name, focus, level, desc, rows) {
  return {
    id, name, focus, level, desc, ready: true,
    items: rows.map(([ex, sets, n, rest]) => (
      EX[ex].t === 't' ? { ex, sets, sec: n, rest } : { ex, sets, reps: n, rest }
    )),
  };
}

